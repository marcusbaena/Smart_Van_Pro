-- Decisão Q4 (grilling 27/10/2026): notificações só dentro do app, em tabela própria.
create table notificacoes (
    notificacao_id bigint generated by default as identity primary key,
    usuario_id     bigint not null references usuarios(usuario_id),
    tipo           varchar(40)  not null,
    titulo         varchar(120) not null,
    mensagem       text         not null,
    referencia_id  bigint,
    lida           boolean      not null,
    data_criacao   timestamp with time zone not null
);

create index idx_notificacoes_usuario_lida on notificacoes (usuario_id, lida);

-- "Registra auditoria" na baixa de mensalidade (UC10) e em outras ações sensíveis.
create table auditorias (
    auditoria_id bigint generated by default as identity primary key,
    usuario_id   bigint references usuarios(usuario_id),
    acao         varchar(60) not null,
    entidade     varchar(60) not null,
    entidade_id  bigint      not null,
    detalhes     text,
    data_registro timestamp with time zone not null
);
