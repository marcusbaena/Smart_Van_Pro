-- Smart Van Pro — schema inicial
-- Fonte: DBML da seção 6 do CONTEXTO_PROJETO (26/10/2026), incluindo
-- motoristas.endereco_partida_id, rotas.escola_id e rotas.polyline.
-- SQL compatível com PostgreSQL e com H2 em MODE=PostgreSQL (testes).
-- Colunas mapeadas para java.time.Instant usam "timestamp with time zone"
-- (padrão do Hibernate 6+), para o ddl-auto: validate não reclamar.

create table enderecos (
    endereco_id  bigint generated by default as identity primary key,
    logradouro   varchar(255) not null,
    numero       varchar(20)  not null,
    complemento  varchar(100),
    bairro       varchar(100) not null,
    cidade       varchar(100) not null,
    uf           varchar(2)     not null,
    cep          varchar(8)   not null,
    latitude     decimal(10,7),
    longitude    decimal(10,7)
);

create table usuarios (
    usuario_id    bigint generated by default as identity primary key,
    email         varchar(255) not null unique,
    senha_hash    varchar(255) not null,
    nome          varchar(255) not null,
    cpf           varchar(11)  not null unique,
    telefone      varchar(20)  not null,
    tipo          varchar(30)  not null,
    status        varchar(30)  not null,
    data_criacao  timestamp with time zone not null,
    ultimo_acesso timestamp with time zone
);

create table motoristas (
    usuario_id          bigint primary key references usuarios(usuario_id),
    status_validacao    varchar(30) not null,
    endereco_partida_id bigint references enderecos(endereco_id)
);

create table responsaveis (
    usuario_id  bigint primary key references usuarios(usuario_id),
    endereco_id bigint references enderecos(endereco_id)
);

create table administradores (
    usuario_id bigint primary key references usuarios(usuario_id)
);

create table escolas (
    escola_id   bigint generated by default as identity primary key,
    endereco_id bigint not null references enderecos(endereco_id),
    nome        varchar(255) not null,
    telefone    varchar(20)
);

create table alunos (
    aluno_id        bigint generated by default as identity primary key,
    escola_id       bigint references escolas(escola_id),
    nome            varchar(255) not null,
    data_nascimento date not null,
    serie           varchar(30)
);

create table alunos_enderecos (
    aluno_id    bigint not null references alunos(aluno_id),
    endereco_id bigint not null references enderecos(endereco_id),
    tipo        varchar(30) not null,
    principal   boolean not null,
    primary key (aluno_id, endereco_id)
);

create table responsaveis_alunos (
    responsavel_id bigint not null references responsaveis(usuario_id),
    aluno_id       bigint not null references alunos(aluno_id),
    parentesco     varchar(30) not null,
    status_vinculo varchar(30) not null,
    acompanha_rota boolean not null,
    primary key (responsavel_id, aluno_id)
);

create table veiculos (
    veiculo_id   bigint generated by default as identity primary key,
    motorista_id bigint not null references motoristas(usuario_id),
    placa        varchar(7)   not null unique,
    modelo       varchar(100) not null,
    ano          integer      not null,
    capacidade   integer      not null,
    tipo         varchar(30)  not null
);

create table motoristas_escolas (
    motorista_id bigint not null references motoristas(usuario_id),
    escola_id    bigint not null references escolas(escola_id),
    primary key (motorista_id, escola_id)
);

create table documentos (
    documento_id  bigint generated by default as identity primary key,
    motorista_id  bigint not null references motoristas(usuario_id),
    veiculo_id    bigint references veiculos(veiculo_id),
    tipo          varchar(30)  not null,
    chave_arquivo varchar(255) not null,
    data_envio    timestamp with time zone not null,
    validade      date,
    status        varchar(30)  not null,
    motivo_recusa text
);

create table validacoes (
    validacao_id     bigint generated by default as identity primary key,
    administrador_id bigint not null references administradores(usuario_id),
    motorista_id     bigint not null references motoristas(usuario_id),
    data_validacao   timestamp with time zone not null,
    decisao          varchar(30) not null,
    parecer          text
);

create table contratos (
    contrato_id                   bigint generated by default as identity primary key,
    responsavel_id                bigint not null references responsaveis(usuario_id),
    motorista_id                  bigint not null references motoristas(usuario_id),
    aluno_id                      bigint not null references alunos(aluno_id),
    valor_mensal                  decimal(10,2) not null,
    data_inicio                   date not null,
    status                        varchar(30) not null,
    data_solicitacao_cancelamento date,
    data_encerramento_efetivo     date,
    solicitante_cancelamento      varchar(30),
    motivo_cancelamento           text
);

create table mensalidades (
    mensalidade_id bigint generated by default as identity primary key,
    contrato_id    bigint not null references contratos(contrato_id),
    competencia    date not null,
    valor          decimal(10,2) not null,
    vencimento     date not null,
    status         varchar(30) not null,
    data_pagamento date,
    constraint uk_mensalidade_contrato_competencia unique (contrato_id, competencia)
);

create table rotas (
    rota_id                bigint generated by default as identity primary key,
    motorista_id           bigint not null references motoristas(usuario_id),
    veiculo_id             bigint not null references veiculos(veiculo_id),
    escola_id              bigint not null references escolas(escola_id),
    data_rota              date not null,
    tipo                   varchar(30) not null,
    status                 varchar(30) not null,
    horario_inicio         time,
    horario_fim            time,
    tempo_estimado_minutos integer,
    distancia_km           decimal(10,2),
    otimizada              boolean not null,
    polyline               text
);

create table paradas_rota (
    parada_id         bigint generated by default as identity primary key,
    rota_id           bigint not null references rotas(rota_id),
    aluno_id          bigint references alunos(aluno_id),
    endereco_id       bigint not null references enderecos(endereco_id),
    ordem             integer not null,
    horario_previsto  time,
    horario_realizado time,
    tipo_parada       varchar(30) not null,
    constraint uk_parada_rota_ordem unique (rota_id, ordem)
);

create table faltas (
    falta_id      bigint generated by default as identity primary key,
    aluno_id      bigint not null references alunos(aluno_id),
    data_falta    date not null,
    motivo        text,
    data_registro timestamp with time zone not null,
    constraint uk_falta_aluno_data unique (aluno_id, data_falta)
);

create index idx_contratos_motorista_status on contratos (motorista_id, status);
create index idx_contratos_responsavel on contratos (responsavel_id);
create index idx_mensalidades_status_vencimento on mensalidades (status, vencimento);
create index idx_rotas_motorista_data on rotas (motorista_id, data_rota);
